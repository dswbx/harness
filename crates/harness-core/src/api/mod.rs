//! Public, transport-neutral API of the Harness core: Commands in, Events out.
//! Everything here is exported to TypeScript (see `export_ts`).
//!
//! The types live in submodules by domain; everything is re-exported flat, so paths stay
//! `harness_core::api::X`.

mod agents;
mod app_event;
mod command;
mod comments;
mod error;
mod event;
mod frontend;
mod git;
mod result;
mod rules;
mod session;
mod settings;
mod shared;

pub use agents::*;
pub use app_event::*;
pub use command::*;
