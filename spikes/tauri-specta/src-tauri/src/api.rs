use serde::{Deserialize, Serialize};
use specta::Type;
use specta_typescript::Number;

/// u64 -> TS `number` (explicit opt-in; safe up to 2^53). See docs.
#[derive(Debug, Clone, Serialize, Deserialize, Type)]
#[serde(tag = "type")]
pub enum Command {
    Ping { text: String },
    CreateSession { name: String },
    Prompt { session_id: String, text: String },
    Cancel { session_id: String },
}

#[derive(Debug, Clone, Serialize, Deserialize, Type)]
#[serde(tag = "type")]
pub enum EventKind {
    SessionCreated { name: String },
    MessageChunk { text: String },
    ToolCall { id: String, name: String },
    Error { message: String },
    Heartbeat,
}

#[derive(Debug, Clone, Serialize, Deserialize, Type)]
pub struct Event {
    #[specta(type = Number)]
    pub seq: u64,
    pub session_id: String,
    pub kind: EventKind,
}

/// Single place to build the type collection (used by bin + test).
pub fn types() -> specta::Types {
    specta::Types::default().register::<Command>().register::<Event>()
}

pub fn export_ts(path: &str) {
    specta_typescript::Typescript::default()
        .header("// @generated by specta. DO NOT EDIT.\n/* eslint-disable */")
        .export_to(path, &types(), specta_serde::Format)
        .expect("ts export");
}
